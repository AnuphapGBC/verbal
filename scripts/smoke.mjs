import assert from 'node:assert/strict';
const base='http://127.0.0.1:5173';
const home=await fetch(base);
assert.equal(home.status,200);
assert.match(await home.text(),/Verbal/);
const session=await fetch(`${base}/api/session`);
assert.equal(session.status,200);
assert.equal((await session.json()).user,null);
const response=await fetch(`${base}/api/tutors`);
assert.equal(response.status,200);
const {tutors,languages}=await response.json();
assert.ok(tutors.length>=6);
assert.ok(languages.length>=6);
assert.ok(tutors.every(t=>typeof t.isDemo==='boolean'&&typeof t.price==='number'));
assert.ok(!JSON.stringify(tutors).includes('password'));
const filtered=await fetch(`${base}/api/tutors?language=Spanish&maxPrice=25`);
assert.equal(filtered.status,200);
assert.ok((await filtered.json()).tutors.every(t=>t.language==='Spanish'&&t.price<=25));
const missing=await fetch(`${base}/api/tutors/99999999`);
assert.equal(missing.status,404);
const health=await fetch(`${base}/api/health`);
assert.equal((await health.json()).database,'connected');
console.log('PASS: frontend, API proxy, session, tutor data, filters, errors, and PostgreSQL health.');
